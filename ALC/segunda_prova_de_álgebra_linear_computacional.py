# Classe Matriz para representar e operar com matrizes
class Matriz:
    def __init__(self, dados):
        # Inicializa a matriz com os dados fornecidos
        self.dados = np.array(dados)
        self.linhas, self.colunas = self.dados.shape

    def transposta(self):
        # Retorna a transposta da matriz
        return Matriz(self.dados.T)

    def __mul__(self, outra):
        # Multiplica duas matrizes
        if self.colunas != outra.linhas:
            raise ValueError("O número de colunas na primeira matriz deve ser igual ao número de linhas na segunda matriz.")
        dados_resultado = np.dot(self.dados, outra.dados)
        return Matriz(dados_resultado)

    def svd(self):
        # Calcula a decomposição em valores singulares (SVD) da matriz usando a biblioteca NumPy
        U, s, Vt = np.linalg.svd(self.dados)
        # Converte s para uma matriz diagonal
        S = np.zeros((self.linhas, self.colunas))
        S[:min(self.linhas, self.colunas), :min(self.linhas, self.colunas)] = np.diag(s)
        # Retorna as matrizes U, S (valores singulares) e Vt (transposta de V)
        return Matriz(U), Matriz(S), Matriz(Vt)

def calcular_numero_condicao(matriz):
    # Calcula o número de condição da matriz usando a decomposição em valores singulares (SVD)
    _, S, _ = matriz.svd()
    # Obtém os valores singulares
    valores_singulares = np.diag(S.dados)
    # Calcula o número de condição
    maior_valor_singular = valores_singulares[0]
    menor_valor_singular = valores_singulares[-1]
    numero_condicao = maior_valor_singular / menor_valor_singular
    return numero_condicao

