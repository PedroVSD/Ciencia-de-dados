# Implementação do método SOR
def metodo_SOR(A, b, omega, epsilon, max_iteracoes):
    """
    Método de Sobrerrelaxação Sucessiva (SOR) para resolver sistemas lineares.

    Parâmetros:
    A (ndarray): Matriz dos coeficientes.
    b (ndarray): Vetor dos termos independentes.
    omega (float): Parâmetro de relaxação.
    epsilon (float): Critério de parada (tolerância para o erro).
    max_iteracoes (int): Número máximo de iterações.

    Retorna:
    tuple: Vetor solução e número de iterações realizadas.
    """
    n = len(b)  # Número de elementos no vetor b
    x = np.zeros(n)  # Vetor inicial (pode ser qualquer valor inicial)
    x_anterior = np.zeros(n)  # Vetor da iteração anterior
    erro = float('inf')  # Inicializa o erro com infinito
    iteracoes = 0  # Contador de iterações

    while erro > epsilon and iteracoes < max_iteracoes:
        # Realiza uma iteração do método SOR
        for i in range(n):
            sigma = sum(A[i][j] * x[j] for j in range(n) if j != i)  # Soma dos produtos dos coeficientes A e das estimativas de x
            x[i] = (1 - omega) * x[i] + (omega / A[i][i]) * (b[i] - sigma)  # Atualiza x[i] com o valor calculado

        # Calcula o erro
        erro = np.linalg.norm(x - x_anterior, ord=np.inf)  # Calcula o erro como a norma infinita da diferença entre x e x_anterior
        x_anterior[:] = x  # Atualiza x_anterior com os valores de x
        iteracoes += 1  # Incrementa o contador de iterações

    return x, iteracoes  # Retorna o vetor solução e o número de iterações realizadas

# Método para encontrar o omega ótimo usando busca linear
def encontrar_WOtimo(A, b, epsilon, max_iteracoes):
    """
    Encontra o valor ótimo de omega para o método SOR usando busca linear.

    Parâmetros:
    A (ndarray): Matriz dos coeficientes.
    b (ndarray): Vetor dos termos independentes.
    epsilon (float): Critério de parada (tolerância para o erro).
    max_iteracoes (int): Número máximo de iterações.

    Retorna:
    float: Valor ótimo de omega.
    """
    omega_min = 1.0  # Valor mínimo de omega
    omega_max = 2.0  # Valor máximo de omega
    incremento = 0.01  # Incremento para busca linear
    num_iteracoes_min = float('inf')  # Inicializa o número mínimo de iterações com infinito
    WOtimo = omega_min  # Inicializa o valor ótimo de omega

    # Realiza a busca linear para encontrar o omega ótimo
    for omega in np.arange(omega_min, omega_max + incremento, incremento):
        _, num_iteracoes = metodo_SOR(A, b, omega, epsilon, max_iteracoes)  # Executa o método SOR com o valor atual de omega
        if num_iteracoes < num_iteracoes_min:
            num_iteracoes_min = num_iteracoes  # Atualiza o número mínimo de iterações
            WOtimo = omega  # Atualiza o valor ótimo de omega

    return WOtimo  # Retorna o valor ótimo de omega

