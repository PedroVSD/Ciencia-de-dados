def verificar_condicoes(A):
    """
    Verifica se a matriz A atende às condições necessárias para a decomposição QR.

    Parâmetros:
    A (numpy.ndarray): Matriz a ser verificada.

    Retorna:
    bool: True se a matriz atender às condições, False caso contrário.
    """
    m, n = A.shape  # Obtém as dimensões da matriz A

    # Condição 1: A matriz deve ser quadrada ou retangular (m >= n)
    if m < n:  # Verifica se o número de linhas é menor que o número de colunas
        print("Erro: A matriz não é retangular (número de linhas < número de colunas).")
        return False  # Retorna False se a condição não for atendida

    # Condição 2: A matriz deve ter posto completo
    for i in range(n):
        if np.all(A[:, i] == 0):  # Verifica se alguma coluna é completamente zero
            print("Erro: A matriz não tem posto completo.")
            return False  # Retorna False se a condição não for atendida

    return True  # Retorna True se todas as condições forem atendidas

def decomposicao_QR(A):
    """
    Realiza a decomposição QR da matriz A.

    Parâmetros:
    A (numpy.ndarray): Matriz a ser decomposta.

    Retorna:
    tuple: Matrizes Q e R resultantes da decomposição QR.
    """
    m, n = A.shape  # Obtém as dimensões da matriz A

    Q = np.zeros((m, n))  # Inicializa a matriz Q com zeros
    R = np.zeros((n, n))  # Inicializa a matriz R com zeros

    # Implementação da decomposição QR (algoritmo real)
    for j in range(n):  # Itera sobre as colunas de A
        coluna = A[:, j].copy()  # Copia a j-ésima coluna de A
        for k in range(j):  # Itera sobre as colunas anteriores
            produto_escalar = np.dot(Q[:, k], coluna)  # Calcula o produto escalar entre Q[:, k] e a coluna
            coluna = coluna - produto_escalar * Q[:, k]  # Atualiza a coluna
        norma_coluna = np.linalg.norm(coluna)  # Calcula a norma da coluna
        Q[:, j] = coluna / norma_coluna  # Normaliza a coluna e armazena em Q
        for i in range(j + 1):  # Atualiza a matriz R
            R[i, j] = np.dot(Q[:, i], A[:, j])  # Calcula o elemento R[i, j]

    return Q, R  # Retorna as matrizes Q e R

