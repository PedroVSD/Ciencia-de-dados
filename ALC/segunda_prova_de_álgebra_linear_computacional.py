import sympy as sp

def newton_raphson(estimativa_inicial, funcao_expr, tolerancia, max_iteracoes=1000):
    # Define o símbolo 'x' para ser usado nas expressões simbólicas
    x = sp.symbols('x')
    # Converte a expressão simbólica da função em uma função numérica usando numpy
    funcao = sp.lambdify(x, funcao_expr, 'numpy')
    # Calcula a derivada simbólica da função
    derivada_expr = sp.diff(funcao_expr, x)
    # Converte a expressão simbólica da derivada em uma função numérica usando numpy
    derivada = sp.lambdify(x, derivada_expr, 'numpy')

    # Inicializa a estimativa atual com a estimativa inicial fornecida
    estimativa_atual = estimativa_inicial
    # Inicializa a estimativa anterior como None
    estimativa_anterior = None
    # Inicializa o contador de iterações
    iteracoes = 0

    # Loop até que a diferença entre estimativas seja menor que a tolerância ou que não haja estimativa anterior
    while estimativa_anterior is None or abs(estimativa_atual - estimativa_anterior) > tolerancia:
        # Verifica se o número máximo de iterações foi atingido
        if iteracoes >= max_iteracoes:
            raise Exception("Número máximo de iterações atingido")

        # Atualiza a estimativa anterior para a estimativa atual
        estimativa_anterior = estimativa_atual
        # Calcula o valor da função na estimativa anterior
        f = funcao(estimativa_anterior)
        # Calcula o valor da derivada na estimativa anterior
        f_prime = derivada(estimativa_anterior)

        # Verifica se a derivada é zero para evitar divisão por zero
        if f_prime == 0:
            raise Exception("Derivada zero encontrada, escolha uma estimativa inicial diferente")

        # Atualiza a estimativa atual usando a fórmula de Newton-Raphson
        estimativa_atual = estimativa_anterior - f / f_prime
        # Incrementa o contador de iterações
        iteracoes += 1

    # Retorna a estimativa atual, que é a raiz encontrada
    return estimativa_atual

