def resolver_problema_de_leontief(matriz_A, vetor_b):
    """
    Resolve o problema de Leontief dado uma matriz de insumo-produto A e um vetor de demanda final b.

    Parâmetros:
    matriz_A (numpy.ndarray): A matriz de insumo-produto (input-output matrix).
    vetor_b (numpy.ndarray): O vetor de demanda final.

    Retorna:
    numpy.ndarray: O vetor de produção que satisfaz a demanda final.
    """
    # Verificando se a matriz_A é quadrada
    if matriz_A.shape[0] != matriz_A.shape[1]:
        raise ValueError("A matriz de insumo-produto A deve ser quadrada.")

    # Verificando se as dimensões do vetor_b são compatíveis com a matriz_A
    if matriz_A.shape[0] != vetor_b.shape[0]:
        raise ValueError("O vetor de demanda final b deve ter o mesmo número de linhas que a matriz A.")

    # Criando a matriz identidade I
    matriz_identidade = np.identity(matriz_A.shape[0])

    # Calculando a matriz (I - A)
    matriz_I_menos_A = matriz_identidade - matriz_A

    # Calculando a inversa de (I - A)
    try:
        matriz_inversa = np.linalg.inv(matriz_I_menos_A)
    except np.linalg.LinAlgError:
        raise ValueError("A matriz (I - A) não é invertível.")

    # Calculando o vetor de produção c = (I - A)^(-1) * b
    vetor_c = np.dot(matriz_inversa, vetor_b)

    return vetor_c

