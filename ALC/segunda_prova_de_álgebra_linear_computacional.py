import numpy as np

def norma(vetor):
    """
    Calcula a norma euclidiana de um vetor.
    """
    return np.sqrt(np.sum(vetor ** 2))

def metodo_da_potencia(matriz, vetor_inicial, max_iteracoes=1000, tolerancia=1e-10):
    """
    Aplica o método da potência para encontrar o autovalor dominante e o autovetor correspondente.

    Parâmetros:
    matriz (np.ndarray): A matriz quadrada para a qual queremos encontrar o autovalor e autovetor dominante.
    vetor_inicial (np.ndarray): Um vetor inicial para iniciar as iterações.
    max_iteracoes (int): O número máximo de iterações a serem realizadas. Padrão é 1000.
    tolerancia (float): A tolerância para a convergência do autovetor. Padrão é 1e-10.

    Retorna:
    autovalor (float): O autovalor dominante encontrado.
    autovetor (np.ndarray): O autovetor correspondente ao autovalor dominante.
    """
    vetor = vetor_inicial / norma(vetor_inicial)  # Normaliza o vetor inicial

    for iteracao in range(max_iteracoes):
        novo_vetor = np.dot(matriz, vetor)  # Multiplica a matriz pelo vetor
        novo_vetor = novo_vetor / norma(novo_vetor)  # Normaliza o novo vetor

        # Verifica a convergência
        if np.linalg.norm(novo_vetor - vetor) < tolerancia:
            break

        vetor = novo_vetor  # Atualiza o vetor para a próxima iteração

    # Calcula o autovalor dominante
    autovalor = np.dot(vetor.T, np.dot(matriz, vetor)) / np.dot(vetor.T, vetor)

    return autovalor, vetor

def precondicionar_matriz(matriz, sigma):
    """
    Aplica pré-condicionamento à matriz subtraindo sigma vezes a identidade.

    Parâmetros:
    matriz (np.ndarray): A matriz quadrada original.
    sigma (float): O valor a ser subtraído da diagonal da matriz.

    Retorna:
    np.ndarray: A matriz pré-condicionada.
    """
    identidade = np.eye(matriz.shape[0])
    return matriz - sigma * identidade

