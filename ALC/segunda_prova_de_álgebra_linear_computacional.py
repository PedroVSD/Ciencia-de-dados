def decomposicao_LU(A):
    n = A.shape[0]  # Número de linhas da matriz A
    L = np.zeros((n, n))  # Inicializa a matriz L com zeros
    U = np.zeros((n, n))  # Inicializa a matriz U com zeros

    # Verificar se A é quadrada
