    n = len(A)  # Obtém o tamanho da matriz
    for i in range(n):  # Loop sobre as linhas da matriz
        for j in range(i):  # Loop sobre as colunas até a diagonal principal
            if A[i][j] != 0:  # Se algum elemento fora da diagonal principal não for zero
                return False  # Retorna falso, pois a matriz não é triangular superior
    return True  # Se nenhum elemento fora da diagonal principal for diferente de zero, retorna verdadeiro, indicando que a matriz é triangular superior

