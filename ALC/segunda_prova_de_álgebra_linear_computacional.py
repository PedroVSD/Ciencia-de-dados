import numpy as np
import pandas as pd  # Importa a biblioteca pandas para manipulação de dados
from google.colab import files  # Importa o módulo files do Google Colab para upload de arquivos

def is_symmetric(A, tol=1e-10):
    return np.allclose(A, A.T, atol=tol)

def is_positive_definite(A):
    try:
        np.linalg.cholesky(A)
        return True
    except np.linalg.LinAlgError:
        return False

def gradiente_conjugado(A, b, tol=1e-10, max_iter=1000):
    # Inicializa a solução x com zeros
    x = np.zeros_like(b)
    # Calcula o resíduo inicial r = b - Ax
    r = b - np.dot(A, x)
    # Inicializa a direção de busca p com o resíduo inicial
    p = r.copy()
    # Calcula o produto interno inicial do resíduo
    rsold = np.dot(r, r)
    iter_count = 0  # Contador de iterações

    while np.sqrt(rsold) > tol and iter_count < max_iter:
        # Calcula Ap, onde A é a matriz do sistema e p é a direção de busca atual
        Ap = np.dot(A, p)
        # Calcula o fator de passo alpha
        alpha = rsold / np.dot(p, Ap)
        # Atualiza a solução x
        x = x + alpha * p
        # Atualiza o resíduo
        r = r - alpha * Ap
        # Calcula o novo produto interno do resíduo
        rsnew = np.dot(r, r)

        # Verifica a condição de parada baseada na tolerância
        if np.sqrt(rsnew) < tol:
            break

        # Atualiza a direção de busca p
        p = r + (rsnew / rsold) * p
        # Atualiza rsold para a próxima iteração
        rsold = rsnew
        iter_count += 1  # Incrementa o contador de iterações

    return x, iter_count

def gradiente_conjugado_precondicionado(A, b, M, tol=1e-10, max_iter=1000):
    # Inicializa a solução x com zeros
    x = np.zeros_like(b)
    # Calcula o resíduo inicial r = b - Ax
    r = b - np.dot(A, x)
    # Resolve Mz = r para obter z
    z = np.linalg.solve(M, r)
    # Inicializa a direção de busca p com z
    p = z.copy()
    # Calcula o produto interno inicial do resíduo com o precondicionamento
    rsold = np.dot(r, z)
    iter_count = 0  # Contador de iterações

    while np.sqrt(rsold) > tol and iter_count < max_iter:
        # Calcula Ap, onde A é a matriz do sistema e p é a direção de busca atual
        Ap = np.dot(A, p)
        # Calcula o fator de passo alpha
        alpha = rsold / np.dot(p, Ap)
        # Atualiza a solução x
        x = x + alpha * p
        # Atualiza o resíduo
        r = r - alpha * Ap
        # Resolve Mz = r para obter o novo z
        z = np.linalg.solve(M, r)
        # Calcula o novo produto interno do resíduo com o precondicionamento
        rsnew = np.dot(r, z)

        # Verifica a condição de parada baseada na tolerância
        if np.sqrt(rsnew) < tol:
            break

