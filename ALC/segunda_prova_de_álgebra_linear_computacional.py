"""Letra K (Critério das linhas, das colunas e de Sassenfeld)"""

import pandas as pd  # Importa a biblioteca pandas para manipulação de dados
from google.colab import files  # Importa o módulo files do Google Colab para upload de arquivos

def criterio_linhas(matriz):
    """
    Verifica a convergência de uma matriz usando o critério das linhas.

    Parâmetros:
    matriz (list of list of float): Matriz dos coeficientes.

    Retorna:
    bool: True se a convergência for garantida, False caso contrário.
    """
    num_linhas = len(matriz)  # Obtém o número de linhas da matriz
    num_colunas = len(matriz[0])  # Obtém o número de colunas da matriz

    # Itera sobre as linhas
    for i in range(num_linhas):
        elemento_diagonal = abs(matriz[i][i])  # Elemento da diagonal principal
        soma_outros = 0

        # Soma os outros elementos da linha
        for j in range(num_colunas):
            if j != i:  # Ignora o elemento diagonal
                soma_outros += abs(matriz[i][j])

        # Verifica se o critério é atendido
        if elemento_diagonal <= soma_outros:
            return False  # Não converge

    return True  # Converge


def criterio_colunas(matriz):
    """
    Verifica a convergência de uma matriz usando o critério das colunas.

    Parâmetros:
    matriz (list of list of float): Matriz dos coeficientes.

    Retorna:
    bool: True se a convergência for garantida, False caso contrário.
    """
    num_linhas = len(matriz)  # Obtém o número de linhas da matriz
    num_colunas = len(matriz[0])  # Obtém o número de colunas da matriz

    # Itera sobre as colunas
    for j in range(num_colunas):
        elemento_diagonal = abs(matriz[j][j])  # Elemento da diagonal principal
        soma_outros = 0

        # Soma os outros elementos da coluna
        for i in range(num_linhas):
            if i != j:  # Ignora o elemento diagonal
                soma_outros += abs(matriz[i][j])

        # Verifica se o critério é atendido
        if elemento_diagonal <= soma_outros:
            return False  # Não converge

    return True  # Converge


class ResultadoSassenfeld:
    """
    Classe para armazenar o resultado do critério de Sassenfeld.
    """
    def __init__(self, criterio_aplicavel, criterio_atendido, max_beta):
        self.criterio_aplicavel = criterio_aplicavel  # Se o critério é aplicável
        self.criterio_atendido = criterio_atendido  # Se o critério é atendido
        self.max_beta = max_beta  # O valor máximo de beta


def criterio_sassenfeld(matriz_coeficientes):
    """
    Verifica a convergência de uma matriz usando o critério de Sassenfeld.

    Parâmetros:
    matriz_coeficientes (list of list of float): Matriz dos coeficientes.

    Retorna:
    ResultadoSassenfeld: Resultado do critério de Sassenfeld.
    """
    n = len(matriz_coeficientes)  # Obtém o número de linhas da matriz
    betas = [0] * n  # Inicializa a lista de betas

    # Verifica se os coeficientes na diagonal principal são positivos
    criterio_aplicavel = True
    for i in range(n):
        if matriz_coeficientes[i][i] <= 0:  # Se algum coeficiente diagonal é não positivo
            criterio_aplicavel = False
            break

    if not criterio_aplicavel:
        return ResultadoSassenfeld(False, False, 0)  # Retorna resultado se critério não for aplicável

    # Calcula os betas para cada linha
    for i in range(n):
        soma = 0.0
        for j in range(n):
            if j != i:
                soma += abs(matriz_coeficientes[i][j])
        betas[i] = soma / abs(matriz_coeficientes[i][i])

    # Encontra o valor máximo de beta
    max_beta = max(betas)

    # Verifica se os betas satisfazem o critério de Sassenfeld
    criterio_atendido = max_beta < 1.0

    return ResultadoSassenfeld(True, criterio_atendido, max_beta)  # Retorna o resultado do critério


