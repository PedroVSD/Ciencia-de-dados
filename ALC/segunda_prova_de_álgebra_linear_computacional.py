# Função para resolver um sistema linear usando o método de Jacobi
def jacobi(A, b, tolerancia, maxIteracoes):
    n = A.shape[0]  # Número de linhas da matriz A
    x = np.zeros(n)  # Vetor de solução inicial
    x_novo = np.zeros(n)  # Vetor de solução para a nova iteração
    iter = 0  # Contador de iterações
    erro = float('inf')  # Inicializa o erro como infinito

    # Loop principal do método de Jacobi
    while erro > tolerancia and iter < maxIteracoes:
        np.copyto(x_novo, x)  # Copia o vetor x para x_novo

        # Atualiza as soluções
        for i in range(n):
            soma = 0.0
            for j in range(n):
                if j != i:
                    soma += A[i, j] * x[j]  # Calcula a soma dos produtos
            x_novo[i] = (b[i] - soma) / A[i, i]  # Atualiza a solução para x_i

        erro = np.max(np.abs(x_novo - x))  # Calcula o erro absoluto máximo
        np.copyto(x, x_novo)  # Copia x_novo para x
        iter += 1  # Incrementa o contador de iterações

    return x  # Retorna a solução

