# Função para verificar o critério de Sassenfeld
def criterio_sassenfeld(A):
    n = A.shape[0]  # Obtém o número de linhas da matriz A
    beta = np.zeros(n)  # Inicializa um vetor para armazenar os valores de beta
    max_beta = 0  # Inicializa o valor máximo de beta

    # Loop para calcular os valores de beta para cada linha de A
    for i in range(n):
        soma = 0
        # Calcula a soma dos valores absolutos dos elementos fora da diagonal
        for j in range(n):
            if j != i:
                soma += abs(A[i, j])
        # Calcula beta para a linha i
        beta[i] = soma / abs(A[i, i])
        # Atualiza o valor máximo de beta
        if beta[i] > max_beta:
            max_beta = beta[i]

    # Retorna True se o maior valor de beta for menor que 1, indicando que o critério de Sassenfeld é satisfeito
    return max_beta < 1

