def cholesky(A):
    n = A.shape[0]  # Número de linhas/colunas da matriz A
    L = np.zeros((n, n))  # Inicializa a matriz L com zeros

    # Verificar se A é simétrica
    if not np.allclose(A, A.T):  # Verifica se A é aproximadamente igual à sua transposta
        print("A matriz fornecida não é simétrica.")  # Mensagem de erro
        return None  # Retorna None

    # Verificar se A é definida positiva
    for i in range(n):
        sum = 0.0  # Inicializa a soma dos quadrados dos elementos da linha i
        for k in range(i):
            sum += L[i][k] ** 2  # Adiciona o quadrado de L[i][k] à soma
        diagonal = A[i, i] - sum  # Calcula o valor da diagonal de L
        if diagonal <= 0:  # Verifica se a diagonal é menor ou igual a zero
            print("A matriz fornecida não é definida positiva.")  # Mensagem de erro
            return None  # Retorna None
        L[i, i] = np.sqrt(diagonal)  # Define o elemento diagonal de L
        for j in range(i + 1, n):
            sum = 0.0  # Inicializa a soma dos produtos
            for k in range(i):
                sum += L[i, k] * L[j, k]  # Adiciona o produto L[i, k] * L[j, k] à soma
            if L[i, i] == 0:  # Verifica se o elemento diagonal de L é zero
                print("A matriz fornecida não é definida positiva.")  # Mensagem de erro
                return None  # Retorna None
            L[j, i] = (A[j, i] - sum) / L[i, i]  # Calcula o elemento fora da diagonal de L

    return L  # Retorna a matriz L


