def distancia(elemento, x):
    distan = 0
    for i in range(len(elemento)):
        distan += (elemento[i] - x[i])**2
    return distan**0.5


def elementosMaisproximos(elemento, x_train, y_train, verificacao_y):
    min_distancia = float('inf')
    classe_mais_proxima = 0
    ind_mais_pro = 0

    for i in range(np.shape(x_train)[0]):
        if verificacao_y[i]:
            distancia_atual = distancia(elemento, x_train[i])
            if distancia_atual < min_distancia:
                min_distancia = distancia_atual
                classe_mais_proxima = y_train[i]
                ind_mais_pro = i

    verificacao_y[ind_mais_pro] = False

    return classe_mais_proxima, verificacao_y


