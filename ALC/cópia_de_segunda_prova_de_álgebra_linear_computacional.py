import numpy as np
import pandas as pd
from google.colab import files

def determinante(A):
    return np.linalg.det(A)

def decomposicao_LU(A):
    n = A.shape[0]
    L = np.zeros((n, n))
    U = np.zeros((n, n))

    # Verificar se A é quadrada
    if A.shape[0] != A.shape[1]:
        print("A matriz fornecida não é quadrada.")
        return None, None

    # Verificar se A é não singular
    if determinante(A) == 0:
        print("A matriz fornecida é singular (determinante igual a zero).")
        return None, None

    # Fatoração LU
    for i in range(n):
        # Matriz U
        for j in range(i, n):
            sum = 0
            for k in range(i):
                sum += L[i, k] * U[k, j]
            U[i, j] = A[i, j] - sum

        # Matriz L
        L[i, i] = 1  # Diagonal principal de L é 1
        for j in range(i + 1, n):
            sum = 0
            for k in range(i):
                sum += L[j, k] * U[k, i]
            L[j, i] = (A[j, i] - sum) / U[i, i]

    return L, U


