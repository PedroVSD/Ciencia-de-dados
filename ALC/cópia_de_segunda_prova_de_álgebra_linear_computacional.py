import numpy as np

def svd_manual(A):
    # Passo 1: Calcular A * A^T e A^T * A
    AAT = np.dot(A, A.T)
    ATA = np.dot(A.T, A)

    # Passo 2: Calcular os autovalores e autovetores de A * A^T (para U)
    autovalores_AAT, autovetores_U = np.linalg.eig(AAT)

    # Passo 3: Calcular os autovalores e autovetores de A^T * A (para V)
    autovalores_ATA, autovetores_V = np.linalg.eig(ATA)

    # Passo 4: Ordenar os autovalores e autovetores em ordem decrescente
    indices_ordenados_AAT = np.argsort(autovalores_AAT)[::-1]
    autovalores_ordenados_AAT = autovalores_AAT[indices_ordenados_AAT]
    U = autovetores_U[:, indices_ordenados_AAT]

    indices_ordenados_ATA = np.argsort(autovalores_ATA)[::-1]
    autovalores_ordenados_ATA = autovalores_ATA[indices_ordenados_ATA]
    V = autovetores_V[:, indices_ordenados_ATA]

    # Passo 5: Calcular os valores singulares
    valores_singulares = np.sqrt(autovalores_ordenados_AAT)

    # Passo 6: Construir a matriz Sigma como uma matriz diagonal
    Sigma = np.zeros((A.shape[0], A.shape[1]))
    np.fill_diagonal(Sigma, valores_singulares)

    # Passo 7: Calcular U e V
    U = autovetores_U[:, indices_ordenados_AAT]
    V = autovetores_V[:, indices_ordenados_ATA]

    # Passo 8: Normalizar U e V
    U = np.dot(A, np.dot(V, np.linalg.pinv(Sigma)))  # Corrigindo U baseado em A, V e Sigma
    V = V / np.linalg.norm(V, axis=0)

    # Transpor V para obter V^T
    VT = V.T

    # Verificar a reconstrução da matriz original
    A_reconstructed = np.dot(U, np.dot(Sigma, VT))
    print("\nMatriz A reconstruída:")
    print(A_reconstructed)

    return U, Sigma, VT

