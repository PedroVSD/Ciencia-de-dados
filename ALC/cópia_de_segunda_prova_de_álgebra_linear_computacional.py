import numpy as np

def gram_schmidt(matriz):
    # Verificar se a matriz é válida
    if not isinstance(matriz, np.ndarray):
        raise ValueError("A entrada deve ser uma matriz numpy.")

    if matriz.ndim != 2:
        raise ValueError("A matriz de entrada deve ser bidimensional.")

    # Verificar se os vetores são linearmente independentes
    if np.linalg.matrix_rank(matriz) < matriz.shape[1]:
        raise ValueError("Os vetores fornecidos não são linearmente independentes.")

    # Obter o número de vetores (colunas) na matriz
    n = matriz.shape[1]

    # Inicializar a matriz para os vetores ortogonais
    Q = np.zeros_like(matriz, dtype=float)

    # Iterar sobre cada vetor na matriz
    for i in range(n):
        # Começar com o vetor atual
        u = matriz[:, i]

        # Subtrair as projeções de u em cada um dos vetores q anteriores
        for j in range(i):
            u -= np.dot(Q[:, j], matriz[:, i]) * Q[:, j]

        # Verificar se a norma é zero (o que significaria que os vetores são linearmente dependentes)
        norma_u = np.linalg.norm(u)
        if norma_u == 0:
            raise ValueError(f"O vetor {i} é uma combinação linear dos vetores anteriores, indicando dependência linear.")

        # Normalizar o vetor
        Q[:, i] = u / norma_u

    return Q

