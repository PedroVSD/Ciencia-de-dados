import numpy as np
from sympy import symbols, Matrix, det

def polinomio_caracteristico(A):
    # Verifique se a matriz é quadrada
    if A.shape[0] != A.shape[1]:
        raise ValueError("A matriz deve ser quadrada")

    # Obtenha a ordem da matriz
    n = A.shape[0]

    # Defina a variável simbólica λ
    λ = symbols('λ')

    # Construa a matriz simbólica A - λI
    I = np.eye(n)
    A_lambda_I = Matrix(A) - λ * Matrix(I)

    # Calcule o determinante
    polinomio = det(A_lambda_I)

    return polinomio

