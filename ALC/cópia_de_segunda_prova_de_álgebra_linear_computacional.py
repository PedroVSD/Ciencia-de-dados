# Função para dividir o dataset em treinamento e teste
def train_test_split(X, y, test_size=0.2, random_state=None):
    if random_state is not None:
        np.random.seed(random_state)
    indices = np.arange(X.shape[0])
    np.random.shuffle(indices)
    split = int(X.shape[0] * (1 - test_size))
    train_indices = indices[:split]
    test_indices = indices[split:]
    return X[train_indices], X[test_indices], y[train_indices], y[test_indices]

# Função para normalizar os dados
def normalize(X, mean=None, std=None):
    if mean is None:
        mean = np.mean(X, axis=0)
    if std is None:
        std = np.std(X, axis=0)
    return (X - mean) / std, mean, std

# Função para calcular a distância Euclidiana
def euclidean_distance(a, b):
    return np.sqrt(np.sum((a - b) ** 2))

# Função para calcular a distância Manhattan
def manhattan_distance(a, b):
    return np.sum(np.abs(a - b))

# Função para calcular a distância Chebyshev
def chebyshev_distance(a, b):
    return np.max(np.abs(a - b))

# Função para encontrar os k vizinhos mais próximos
def get_neighbors(X_train, y_train, test_instance, k, distance_func):
    distances = []
    for i in range(X_train.shape[0]):
        dist = distance_func(test_instance, X_train[i])
        distances.append((y_train[i], dist))
    distances.sort(key=lambda x: x[1])
    neighbors = distances[:k]
    return [neighbor[0] for neighbor in neighbors]

# Função para fazer a previsão usando KNN
def predict(X_train, y_train, X_test, k, distance_func):
    predictions = []
    for test_instance in X_test:
        neighbors = get_neighbors(X_train, y_train, test_instance, k, distance_func)
        prediction = max(set(neighbors), key=neighbors.count)
        predictions.append(prediction)
    return np.array(predictions)

# Função para calcular a acurácia
