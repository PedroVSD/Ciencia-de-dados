import numpy as np
import pandas as pd
from google.colab import files

def criterio_sassenfeld(A):
    n = A.shape[0]
    beta = np.zeros(n)
    max_beta = 0

    for i in range(n):
        soma = 0
        for j in range(n):
            if j != i:
                soma += abs(A[i, j])
        beta[i] = soma / abs(A[i, i])
        if beta[i] > max_beta:
            max_beta = beta[i]

    return max_beta < 1

def gauss_seidel(A, b, tolerancia, max_iteracoes):
    n = A.shape[0]
    x = np.zeros(n)
    x_anterior = np.zeros(n)
    iteracoes = 0

    if not criterio_sassenfeld(A):
        print("O critério de Sassenfeld não foi satisfeito. O método pode não convergir.")

    while iteracoes < max_iteracoes:
        np.copyto(x_anterior, x)

        for i in range(n):
            soma = 0
            for j in range(n):
                if j != i:
                    soma += A[i, j] * x[j]
            x[i] = (b[i] - soma) / A[i, i]

        erro = np.sum(np.abs(x - x_anterior))
        if erro < tolerancia:
            print(f"Convergiu após {iteracoes + 1} iterações.")
            return x

        iteracoes += 1

    print("O método atingiu o número máximo de iterações.")
    return x

