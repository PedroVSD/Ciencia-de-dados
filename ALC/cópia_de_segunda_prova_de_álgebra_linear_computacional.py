def verificar_condicoes(A):
    m, n = A.shape

    # Condição 1: A matriz deve ser quadrada ou retangular (m >= n)
    if m < n:
        print("Erro: A matriz não é retangular (número de linhas < número de colunas).")
        return False

    # Condição 2: A matriz deve ter posto completo
    for i in range(n):
        if np.all(A[:, i] == 0):
            print("Erro: A matriz não tem posto completo.")
            return False

    return True

def decomposicao_QR(A):
    m, n = A.shape

    Q = np.zeros((m, n))
    R = np.zeros((n, n))

    # Implementação da decomposição QR (algoritmo real)
    for j in range(n):
        coluna = A[:, j].copy()
        for k in range(j):
            produto_escalar = np.dot(Q[:, k], coluna)
            coluna = coluna - produto_escalar * Q[:, k]
        norma_coluna = np.linalg.norm(coluna)
        Q[:, j] = coluna / norma_coluna
        for i in range(j + 1):
            R[i, j] = np.dot(Q[:, i], A[:, j])

    return Q, R

