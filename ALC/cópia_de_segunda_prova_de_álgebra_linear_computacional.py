import numpy as np

def is_symmetric(A, tol=1e-10):
    return np.allclose(A, A.T, atol=tol)

def is_positive_definite(A):
    try:
        np.linalg.cholesky(A)
        return True
    except np.linalg.LinAlgError:
        return False

def gradient_descent(A, b, tol=1e-10, max_iter=1000):
    x = np.zeros_like(b)
    r = b - np.dot(A, x)
    iter_count = 0

    while np.linalg.norm(r) > tol and iter_count < max_iter:
        alpha = np.dot(r, r) / np.dot(r, np.dot(A, r))
        x = x + alpha * r
        r = b - np.dot(A, x)
        iter_count += 1

    return x, iter_count

def preconditioned_gradient_descent(A, b, M, tol=1e-10, max_iter=1000):
    x = np.zeros_like(b)
    r = b - np.dot(A, x)
    z = np.linalg.solve(M, r)
    iter_count = 0

    while np.linalg.norm(r) > tol and iter_count < max_iter:
        alpha = np.dot(r, z) / np.dot(z, np.dot(A, z))
        x = x + alpha * z
        r = b - np.dot(A, x)
        z = np.linalg.solve(M, r)
        iter_count += 1

    return x, iter_count

