def newton_raphson(estimativa_inicial, funcao, derivada, tolerancia):
    estimativa_atual = estimativa_inicial
    estimativa_anterior = None

    while estimativa_anterior is None or abs(estimativa_atual - estimativa_anterior) > tolerancia:
        estimativa_anterior = estimativa_atual
        f = funcao(estimativa_anterior)
        f_prime = derivada(estimativa_anterior)
        estimativa_atual = estimativa_anterior - f / f_prime

    return estimativa_atual

