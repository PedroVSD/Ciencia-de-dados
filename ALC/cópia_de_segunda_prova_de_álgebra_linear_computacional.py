def criterio_linhas(matriz):
    """
    Verifica a convergência de uma matriz usando o critério das linhas.

    Parâmetros:
    matriz (list of list of float): Matriz dos coeficientes.

    Retorna:
    bool: True se a convergência for garantida, False caso contrário.
    """
    num_linhas = len(matriz)
    num_colunas = len(matriz[0])

    # Itera sobre as linhas
    for i in range(num_linhas):
        elemento_diagonal = abs(matriz[i][i])  # Elemento da diagonal principal
        soma_outros = 0

        # Soma os outros elementos da linha
        for j in range(num_colunas):
            if j != i:  # Ignora o elemento diagonal
                soma_outros += abs(matriz[i][j])

        # Verifica se o critério é atendido
        if elemento_diagonal <= soma_outros:
            return False  # Não converge

    return True  # Converge


